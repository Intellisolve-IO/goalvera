#!/usr/bin/env python3
"""Regenerate main/goalvera_logo.c from the goalvera homepage logo.

Source: site/img/goalvera-B2-large-oneword-dark.svg (the www.goalvera.app
lockup: G mark + "goalvera" wordmark, white on teal). The teal background
rect is dropped so the lockup sits on the recorder's dark header, the
result is trimmed to its ink and scaled to HEIGHT px, then written as an
LVGL 9 ARGB8888 image (lv_image_dsc_t goalvera_logo).

    pip install cairosvg pillow
    python3 tools/make_logo.py            # from firmware/recorder-idf
"""
import io
import pathlib
import re
import sys

import cairosvg
from PIL import Image

HEIGHT = int(sys.argv[1]) if len(sys.argv) > 1 else 28
HERE = pathlib.Path(__file__).resolve().parent
SVG = HERE.parents[2] / "site" / "img" / "goalvera-B2-large-oneword-dark.svg"
OUT = HERE.parent / "main" / "goalvera_logo.c"

svg = re.sub(r"<rect[^>]*/>", "", SVG.read_text(), count=1)
png = cairosvg.svg2png(bytestring=svg.encode(), output_width=516 * 8, output_height=129 * 8)
im = Image.open(io.BytesIO(png)).convert("RGBA")
im = im.crop(im.getbbox())
w = round(im.width * HEIGHT / im.height)
im = im.resize((w, HEIGHT), Image.LANCZOS)

data = bytearray()
for r, g, b, a in im.getdata():
    data += bytes((b, g, r, a))  # LVGL ARGB8888 is B, G, R, A in memory

rows = [", ".join(f"0x{x:02x}" for x in data[i:i + 16]) for i in range(0, len(data), 16)]
OUT.write_text(f"""/* Generated by tools/make_logo.py from site/img/goalvera-B2-large-oneword-dark.svg.
 * Do not edit by hand. {w}x{HEIGHT} ARGB8888. */
#include "lvgl.h"

static const uint8_t goalvera_logo_map[] = {{
    {(","+chr(10)+"    ").join(rows)},
}};

const lv_image_dsc_t goalvera_logo = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_ARGB8888,
        .w = {w},
        .h = {HEIGHT},
        .stride = {w * 4},
    }},
    .data_size = sizeof goalvera_logo_map,
    .data = goalvera_logo_map,
}};
""")
im.save(HERE.parent / "docs" / "goalvera_logo_preview.png") if "--preview" in sys.argv else None
print(f"wrote {OUT.relative_to(HERE.parent)} ({w}x{HEIGHT})")
